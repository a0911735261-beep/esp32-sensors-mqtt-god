#ifndef EPDIF_H
#define EPDIF_H

#include <Arduino.h>

// ESP32 DevKit / ESP32-WROOM-32 pin definition.
// The Waveshare 2.9inch e-Paper (B) V4 uses SPI mode 0.
// These pins are the common course wiring:
// DIN/MOSI=23, SCK=18, CS=27, DC=26, RST=25, BUSY=34.
#define RST_PIN         25
#define DC_PIN          26
#define CS_PIN          27
#define BUSY_PIN        34

// The 8-pin Waveshare module is powered from VCC, so no separate
// power-control GPIO is needed.  Keep this disabled in the interface code.
#define PWR_PIN         -1

class EpdIf {
public:
    EpdIf(void);
    ~EpdIf(void);

    static int  IfInit(void);
    static void DigitalWrite(int pin, int value); 
    static int  DigitalRead(int pin);
    static void DelayMs(unsigned int delaytime);
    static void SpiTransfer(unsigned char data);
};

#endif
